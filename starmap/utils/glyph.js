export function drawGlyph(cv,n,x,y,r,c){
  const g=GL[n]; if(!g)return
  try{cv.setPaint({color:c,line_width:2})}catch(e){return}
  for(let i=0;i<g.r.length;i++){
    const cx=x+g.r[i][0]*r, cy=y+g.r[i][1]*r, rr=g.r[i][2]*r
    let px=cx+rr,py=cy
    for(let k=1;k<=8;k++){
      const a=k*Math.PI/4
      const nx=cx+rr*Math.cos(a), ny=cy+rr*Math.sin(a)
      cv.drawLine({x1:px|0,y1:py|0,x2:nx|0,y2:ny|0,color:c}); px=nx; py=ny
    }
  }
  for(let i=0;i<g.s.length;i++){const q=g.s[i]
    cv.drawLine({x1:(x+q[0]*r)|0,y1:(y+q[1]*r)|0,
                 x2:(x+q[2]*r)|0,y2:(y+q[3]*r)|0,color:c})}
}
