const pick = (a, r) => a[Math.floor(r() * a.length)]
// {欄} を埋める。埋まらない欄があれば、その文は使わない
function fill(t, c) {
  let ok = true
  const out = t.replace(/\{(\w+)\}/g, (m, k) => {
    const v = c[k]
    if (v === null || v === undefined || v === '') { ok = false; return '' }
    return String(v)
  })
  return ok ? out : null
}
function pickFill(arr, c, r) {
  const cands = (arr || []).map((t) => fill(t, c)).filter(Boolean)
  return cands.length ? pick(cands, r) : ''
}
const dur = (m) => (m >= 60 ? `${Math.floor(m / 60)}時間${m % 60 ? (m % 60) + '分' : ''}` : `${m}分`)
