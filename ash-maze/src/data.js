function monExp(m) {
  let mult = 1 + 0.15 * m.fl.replace(/[UX]/g, '').length + (m.sp ? 0.2 : 0) + (m.br ? 0.2 : 0) + (m.mr ? 0.1 : 0);
  if (m.boss) mult += 1;
  return Math.round((12 * Math.pow(m.lv, 2.4) + 35) * mult);
}

