let rnd = Math.random;
function setRng(f) { rnd = f; }
function mulberry32(a) {
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function ri(a, b) { return a + Math.floor(rnd() * (b - a + 1)); }   // a..b
function pct(p) { return rnd() * 100 < p; }
function pick(arr) { return arr[Math.floor(rnd() * arr.length)]; }
function dice(d) {                                                  // [n, s, plus]
  if (!d) return 0;
  let t = d[2] || 0;
  for (let i = 0; i < d[0]; i++) t += ri(1, d[1]);
  return t;
}
function dstr(d) { return d[0] + 'd' + d[1] + (d[2] > 0 ? '+' + d[2] : d[2] < 0 ? d[2] : ''); }
function clamp(v, a, b) { return v < a ? a : v > b ? b : v; }
function shuffle(a) {
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}

