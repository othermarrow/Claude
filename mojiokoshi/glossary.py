def key(word):
    """重複を見分けるための、読みを除いた言葉(「反省会(はんせいかい)」→「反省会」)。"""
    return word.split("(")[0].split("（")[0].strip()


def merge(*lists):
    """用語集をまとめる。同じ言葉は最初のものだけ残す(読みの有無は問わない)。"""
    seen, out = set(), []
    for words in lists:
        for w in words:
            k = key(w)
            if k and k not in seen:
                seen.add(k)
                out.append(w)
    return out
