def norm(text):
    return re.sub(r"\s+", "", text or "").strip()


def sentences(text):
    return [s for s in re.split(r"(?<=[。！？!?\n])|\n", norm(text)) if s.strip("。！？!?、")]


def clauses(text):
    return [c for c in re.split(r"[。、！？!?\n]", norm(text)) if len(c) >= 2]


_PARTICLE = "はがをにのでともへやかよねなだ"


def words(text):
    """漢字・カタカナの語。後ろに送りがなが続く漢字（「最近眠れない」の「眠」）は、動詞の一部として外す。"""
    t = norm(text)
    out = []
    for m in re.finditer(r"[" + KANJI + r"]{2,}|[ァ-ヶー]{3,}", t):
        w = m.group(0)
        nxt = t[m.end():m.end() + 1]
        if _K.match(w[-1]) and nxt and re.match(r"[ぁ-ん]", nxt) and nxt not in _PARTICLE:
            w = w[:-1]
        if len(w) >= 2 and w not in _STOP:
            out.append(w)
    return out


def tokens(text):
    """内容のある言葉（漢字・カタカナの語と、漢字＋送りがなの語幹）。"""
    t = norm(text)
    out = set(words(t))
    for m in re.finditer(r"([" + KANJI + r"])([ぁ-ん])", t):
        if m.group(2) not in "にをはがのでともへやかよねな" and m.group(0) not in _STOP:
            out.add(m.group(0))
    return out


def is_question(t):
    if re.search(r"[?？]", t):
        return True
    if re.search(r"(ですか|ますか|ませんか|でしょうか|んですか|のですか|かしら)$", t):
        return True
    if re.search(QWORD, t) and re.search(r"(の|か|かな|だろう|でしょう|って|っけ)$", t) and not re.search(r"(わから|分から|知らな)", t):
        return True
    # 「あなたは誰」「ここはどこ」のように、問いの言葉で終わる短い文も問い
    return bool(len(t) <= 20 and re.search(r"(誰|だれ|どこ|何|なに|なんで|なぜ|どうして|いつ|どれ)$", re.sub(r"[。…\s]+$", "", t)))


def qtype(t):
    for name, pat in QTYPES:
        if re.search(pat, t):
            return name
    return "generic"


def topics_of(text):
    t = norm(text)
    out = []
    for name, pat in TOPICS:
        m = re.search(pat, t)
        if m:
            out.append((name, m.group(1), m.start()))
    return out


def person_in(text):
    m = PERSON_WORD.search(norm(text))
    return m.group(1) if m else ""


def emotion(text):
    """いちばん強い気持ちの語：(名詞, 向き, 打ち消されているか)。なければ None。"""
    t = norm(text)
    for pat, noun, pol in EMOTIONS:
        m = re.search(pat, t)
        if m:
            after = t[m.end():m.end() + 6]
            negated = bool(re.match(r"[ぁ-ん]{0,3}(くない|くなかった|くはない|じゃない|ではない)", after))
            return noun, pol, negated
    return None


def number_in(text):
    m = NUM_RE.search(norm(text))
    if not m:
        return None
    w = m.group(1)
    w = w.translate(str.maketrans("０１２３４５６７８９", "0123456789"))
    if w.isdigit():
        n = int(w)
    else:
        n = _KANJI_NUM.get(w)
    return n if n is not None and 0 <= n <= 10 else None


def name_in(text):
    m = NAME_RE.search(norm(text))
    if not m:
        return ""
    n = (m.group(1) or m.group(2) or "").strip("「」『』。、 ")
    return n if 1 <= len(n) <= 10 and not re.search(r"(わから|ない|秘密|内緒|言いたく)", n) else ""


def read(text):
    """一つの発言を読む。"""
    t = norm(text)
    u = {"text": t, "act": "narrative", "q": "", "topics": topics_of(t), "person": person_in(t),
         "emo": emotion(t), "time": "", "num": number_in(t), "name": name_in(t),
         "self_blame": bool(SELF_BLAME_RE.search(t)), "wish": bool(WISH_RE.search(re.sub(r"[。！!？?…]+$", "", t))),
         "abs": (ABS_RE.search(t).group(1) if ABS_RE.search(t) else ""), "contrast": bool(CONTRAST_RE.search(t)),
         "unknown": bool(UNKNOWN_RE.search(t)), "greet": bool(GREET_RE.match(t))}
    m = TIME_RE.search(t)
    u["time"] = m.group(1) if m else ""
    bare = re.sub(r"[。、！？!?…ー〜\s]+$", "", t)
    if not bare or re.fullmatch(r"[…・.。、ー〜\s]+", t or "…"):
        u["act"] = "dots"
    elif u["greet"] and len(GREET_RE.sub("", t).strip("。、！!ー〜 ")) <= 4:
        u["act"] = "greet"
    elif BYE_RE.match(t):
        u["act"] = "bye"
    elif CALLME_RE.match(t) or (u["name"] and len(t) <= 20):
        u["act"] = "name"
        u["name"] = u["name"] or CALLME_RE.match(t).group(1)
    elif THANKS_RE.search(t) and len(t) <= 16:
        u["act"] = "thanks"
    elif APOLOGY_RE.search(t) and len(t) <= 14:
        u["act"] = "apology"
    elif is_question(t):
        u["act"], u["q"] = "question", qtype(t)
    elif REQUEST_RE.search(t):
        u["act"] = "request"
    elif INSULT_RE.search(t) and len(t) <= 24:
        u["act"] = "insult"
    elif META_RE.search(t):
        u["act"] = "meta"
    elif LAUGH_RE.search(t) and len(LAUGH_RE.sub("", t)) <= 3:
        u["act"] = "laugh"
    elif YES_RE.match(t):
        u["act"] = "yes"
    elif NO_RE.match(t):
        u["act"] = "no"
    elif DENY_RE.match(t):
        u["act"] = "deny"
    elif u["unknown"] and len(t) <= 12:
        u["act"] = "unknown"
    elif FILLER_RE.match(t):
        u["act"] = "filler"
    elif len(bare) <= 3 and not u["topics"] and not u["emo"]:
        u["act"] = "short"
    return u


def facts(said):
    """会話の全体から、相手について確かなことを集める。"""
    f = {"name": "", "first": "", "complaint": "", "likes": [], "fears": [], "living": "", "pets": [],
         "people": {}, "fine": [], "pain": [], "counts": {}, "narr": []}
    counts = {}
    for k, s in enumerate(said):
        t = norm(s)
        u = read(t)
        if u["name"]:
            f["name"] = u["name"]
        if not f["first"] and u["act"] == "narrative":
            f["first"] = t
        if not f.get("first_q") and u["act"] == "question":
            f["first_q"] = t
        if u["act"] == "narrative":
            f["narr"].append((k, t))
            if not f["complaint"] and (u["topics"] or (u["emo"] and u["emo"][1] < 0)):
                f["complaint"] = t
        for m in re.finditer(r"([^、。！？!?はがをにで]{1,10}?)が(大)?好き", t):
            f["likes"].append(m.group(1))
        for m in re.finditer(r"([^、。！？!?はがをにで]{1,10}?)が(怖い|こわい|苦手)", t):
            f["fears"].append(m.group(1))
        if re.search(r"(一人暮らし|ひとり暮らし)", t):
            f["living"] = "一人暮らし"
        for m in re.finditer(r"(猫|ねこ|犬|いぬ|ハムスター|うさぎ|インコ|金魚)", t):
            if m.group(1) not in f["pets"]:
                f["pets"].append(m.group(1))
        p = person_in(t)
        if p:
            f["people"].setdefault(p, []).append((k, t))
        if re.search(r"(大丈夫|平気|元気|問題ない|楽しかった|楽しい|嬉しい|うれしい)", t) and not re.search(r"(ない|なかった)$", t):
            f["fine"].append((k, t))
        e = u["emo"]
        if e and e[1] < 0 and not e[2]:
            f["pain"].append((k, t))
        for w in words(t) + re.findall(r"わからない|分からない|別に|大丈夫|ごめん|すみません|眠れない|怖い", t):
            if w not in _STOP:
                counts[w] = counts.get(w, 0) + 1
    f["counts"] = counts
    if not f["first"]:
        f["first"] = f.get("first_q", "")
    return f


def last_question(contents):
    """ミナモが前の返事でした問い（なければ ""）。"""
    for c in reversed(contents[:-1]):
        if c["role"] == "model":
            t = c["parts"][0]["text"].replace("[間]", "")
            qs = [s for s in re.split(r"(?<=[。？?])", t) if re.search(r"(か。|か？|\?|？)$", s.strip())]
            return qs[-1].strip() if qs else ""
    return ""


def slot_of(q):
    """問いが、どんな答えを待っているか。"""
    if not q:
        return ""
    if re.search(r"0\s*から\s*10|いくつ", q):
        return "scale"
    if re.search(r"お名前|名前を|名前は", q):
        return "name"
    if re.search(r"いつ|何歳|どのくらい|何年|何か月", q):
        return "when"
    if re.search(r"誰|どなた|どの方", q):
        return "who"
    if re.search(r"(続ける|別の話|別のお話)", q) and re.search(r"どちら|どっち", q):
        return "choice"
    if re.search(r"気持ち", q) and re.search(r"何|どんな", q):
        return "feel"
    if re.search(r"(何|なに|どんな|どう|どこ|どれ|どちら)", q):
        return "what"
    if re.search(r"(ですか|ますか|ませんか|でしたか|ましたか)[。？?]?$", q):
        return "yesno"
    return ""


