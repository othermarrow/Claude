_FMT = __import__("string").Formatter()


def fill(tpl, ctx):
    """ctx で欄を埋める。欄が空ならセリフごと使わない（None）。"""
    try:
        keys = [f for _, f, _, _ in _FMT.parse(tpl) if f]
    except ValueError:
        return None
    if any(ctx.get(k) in (None, "") for k in keys):
        return None
    return tpl.format(**{k: ctx[k] for k in keys})


def at(spec, ph, voice):
    """段階・版に合うセリフの列（その段階になければ、手前の段階のもの）。"""
    for k in range(ph, -1, -1):
        if isinstance(spec, dict):
            a = spec.get(voice, [])
            b = spec.get("all", [])
            pool = (list(a[k]) if k < len(a) else []) + (list(b[k]) if k < len(b) else [])
        else:
            pool = list(spec[k]) if k < len(spec) else []
        if pool:
            return pool
    return []


def greet_word(hh):
    h = int(hh) if str(hh).isdigit() else 21
    return "おはようございます" if 4 <= h <= 10 else "こんにちは" if 11 <= h <= 17 else "こんばんは"


def _tod_line(hh):
    h = int(hh) if str(hh).isdigit() else 21
    if 0 <= h <= 3:
        return "こんな夜更けまで、起きていらっしゃるのですね。"
    if 4 <= h <= 9:
        return "朝早くから、ありがとうございます。"
