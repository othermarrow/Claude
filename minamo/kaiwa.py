_HONOR_RE = re.compile("(?<![ァ-ヶ" + KANJI + "])(?<!お)(" + "|".join(sorted(map(re.escape, HONOR), key=len, reverse=True))
                       + ")(?=[がはをにのともへでや、。]|さん|だ|です|なの|$)")


def honor(s):
    return _HONOR_RE.sub(lambda m: HONOR[m.group(1)], s)


_FIRST = r"(私|わたし|僕|ぼく|俺|おれ|あたし)"


def swap(s):
    """相手の言葉の「私」「あなた」を、ミナモの側から言い直す（私 → あなた・ご自分、あなた → 私）。"""
    s = re.sub(r"(あなた|きみ|君|お前|おまえ|ミナモ)", "\x01", s)
    if re.match(_FIRST + r"は" + _FIRST + r"(だ|です)?$", s):          # 私は私です
        return "あなたは、あなた"
    s = re.sub("^" + _FIRST + r"は、?", "", s)
    s = re.sub(_FIRST + r"の", "あなたの", s)
    s = re.sub(_FIRST + r"(が|を|に|と|も|は|だけ|しか|って)", r"ご自分\2", s)
    s = re.sub(_FIRST, "あなた", s)
    s = re.sub(r"(?<![ご])自分", "ご自分", s)
    s = s.replace("\x01", "私")
    return honor(s)


# ミナモが言い直すときの、くだけた言い方 → ていねいな言い方
POLITE = [("死んじゃった", "亡くなってしまった"), ("死んじゃって", "亡くなってしまって"), ("死んだ", "亡くなった"),
          ("ムカついた", "腹が立った"), ("ムカつく", "腹が立つ"), ("むかつく", "腹が立つ"), ("キツい", "つらい"),
          ("きつい", "つらい"), ("めっちゃ", "とても"), ("マジで", "本当に"), ("まじで", "本当に"), ("超", "とても"),
          ("やばい", "大変な"), ("ヤバい", "大変な"), ("ってか", ""), ("てか", "")]
_FILLER = re.compile(r"^(なんか|何か、|別に|べつに|まあ|まぁ|えっと|えーと|あの|あのー|その|うーん|でも|だけど|けど|"
                     r"いや|てか|ていうか|というか|とりあえず|ちょっと、|それで|で、|だって|だから|しかも)、?")


def polite(s):
    s = re.sub(r"が(ムカつ|むかつ)", r"に\1", s)          # 上司がムカつく → 上司に腹が立つ
    s = re.sub(r"(?<=[っんいしきぎ])(て|で)(た|る)$", lambda m: m.group(1) + ("いた" if m.group(2) == "た" else "いる"), s)
    for a, b in POLITE:
        s = s.replace(a, b)
    return s


def core(cl):
    """相手の一節を、ふつうの言い切りにして、主語をミナモの側から言い直したもの（「眠れない」「上司の方に怒られた」）。"""
    raw = _TAIL_PUNCT.sub("", re.sub(r"\s+", "", cl))
    if not raw or re.search(r"[?？]", cl):
        return ""
    raw = _FILLER.sub("", raw) or raw
    s = polite(plain(raw))
    t = te_to_plain(s)
    if t:
        s = t
    if not s or len(s) < 2:
        return ""
    return swap(s)


def echo(cl):
    """相手の一節を、「〜のですね」で受け止める文にする（作れなければ ""）。"""
    if len(re.sub(r"\s+", "", cl)) > 34:
        return ""
    s = core(cl)
    if not s:
        return ""
    # 「〜と思う」「〜気がする」は、思っているのは相手
    m = re.search(r"(.+?)(なんだ|んだ|のだ|だ)?(と|って)(思う|思っている|思ってる|思ってい|感じる|考えている)$", s)
    if m:
        inner = m.group(1)
        if m.group(2):
            inner = inner + ("なのだ" if nominal(inner) else "のだ")
        return f"{inner}と、思っていらっしゃるのですね。"
    m = re.search(r"(.+?)(のかな|かな)$", s)
    if m:
        return f"{m.group(1)}のかもしれない、と感じていらっしゃるのですね。"
    if re.search(r"(かもしれない|かも)$", s):
        return re.sub(r"(かもしれない|かも)$", "かもしれない、と感じていらっしゃるのですね。", s)
    if s.endswith("だ"):
        stem = s[:-1]
        if s.endswith("んだ") or (s.endswith("いだ") and not nominal(stem)):
            return s + "のですね。"                    # 読んだ・泳いだ（過去形）
        return stem + "なのですね。"
    return s + ("なのですね。" if nominal(s) else "のですね。")


def note(cl):
    """相手について覚えておく形（「最近眠れない」「自分が悪いと思っている」）。敬称は残し、ご自分は自分に。"""
    s = core(cl)
    if not s:
        return ""
    s = re.sub(r"^(たぶん|多分|なんか|やっぱり|やっぱ)、?", "", s)
    s = s.replace("ご自分", "自分").replace("あなた", "自分")
    s = re.sub(r"(なんだ|んだ|のだ)?(と|って)(思う|思ってる)$", "と思っている", s)
    return s


def first_person(cl):
    """相手の一節を、ミナモが自分のこととして言う形にする（「眠れない」→「眠れないのです」）。融合で使う。"""
    s = core(cl)
    if not s or len(s) > 30:
        return ""
    s = s.replace("ご自分", "私").replace("あなた", "私")
    m = re.search(r"(.+?)(なんだ|んだ|のだ|だ)?(と|って)(思う|思っている|思ってる|感じる)$", s)
    if m:
        inner = m.group(1) + (("なのだ" if nominal(m.group(1)) else "のだ") if m.group(2) else "")
        return inner + "と思うのです"
    if s.endswith("だ") and not s.endswith(("んだ", "いだ")):
        return s[:-1] + "なのです"
    return s + ("なのです" if nominal(s) else "のです")


