"""ミナモの端末内モデル（2026 年版・1996 年版）が共有する「聞き取り」と「話し方」。

聞き取り（read）
  相手が何をしたか（あいさつ・質問・答え・打ち明け・否定・わからない・怒り・笑い・メタな発言）、
  何の話か（眠り・仕事・家族……）、誰が出てくるか、どんな気持ちか、を読む。
  ミナモが前に聞いたこと（いつから？　0 から 10 で？　はい・いいえ？）への答えも拾う。
  会話の全体から、相手について確かなこと（名前・一人暮らし・飼っていた犬・好きなもの……）を集める。
映し返し（echo）
  相手の文を、敬語の「〜のですね」に、文法どおりに直して返す（眠れなくて → 眠れないのですね）。
話し方（Talk）
  質問には答え、答えは受け止め、打ち明けには映し返し・見立て・問いで応じる。
  怖さは、相手の言葉を正確に覚えていること（何回目か・何分たったか・最初に何と書いたか）と、
  知るはずのないこと（端末の名前・電池）と、少しずつ入れ替わっていく主語から作る。

ネットにも AI にもつながらない。標準ライブラリだけ。
"""

import random
import re

# ==========================================
# 文法：丁寧形 → ふつうの形、映し返しの「〜のですね」
# ==========================================
KANJI = r"一-鿿々"            # 漢字と「々」
_K = re.compile(f"[{KANJI}]")
_KK = re.compile(f"[{KANJI}゠-ヿ]")   # 漢字かカタカナ

# ます形の語幹が「い段」で終わる一段動詞（五段と見分けがつかないものだけ）
ICHIDAN_I = {"でき", "起き", "生き", "感じ", "信じ", "落ち", "過ぎ", "借り", "降り", "浴び", "伸び", "閉じ",
             "飽き", "足り", "満ち", "尽き", "用い", "延び", "似", "見", "居", "着", "煮", "い", "み", "おき",
             "いき", "かんじ", "しんじ", "おち", "すぎ", "かり", "おり", "あび", "のび", "とじ", "あき", "たり",
             "見過ぎ", "寝過ぎ", "生き延び", "落ち込", "強い"}
# い段 → う段・あ段・過去形
_I2U = dict(zip("きぎしちにびみりい", "くぐすつぬぶむるう"))
_I2A = dict(zip("きぎしちにびみりい", "かがさたなばまらわ"))
_I2TA = {"き": "いた", "ぎ": "いだ", "し": "した", "ち": "った", "り": "った", "い": "った",
         "に": "んだ", "び": "んだ", "み": "んだ"}
_E_ROW = set("えけげせぜてでねべぺめれへ")


def _suru(stem):
    """「勉強し」「メモし」のようなサ変の語幹か（「話し」「消し」は五段）。"""
    if stem in ("し",):
        return True
    if not stem.endswith("し"):
        return False
    body = stem[:-1]
    return len(body) >= 2 and all(_KK.match(c) for c in body[-2:])


def _ichidan(stem):
    if stem.endswith(("てい", "でい")):          # 〜ています・〜ていました（いる）
        return True
    if stem in ICHIDAN_I or any(stem.endswith(x) for x in ICHIDAN_I if len(x) >= 2):
        return True
    last = stem[-1]
    if last in _E_ROW:
        return True
    return bool(_K.match(last))       # 寝・見・出 のように送りがなのない語幹


def masu_to_plain(stem, form):
    """ます形の語幹を、ふつうの形にする。form: dict（する）・neg（しない）・past（した）・negpast（しなかった）。"""
    if not stem:
        return stem
    if stem in ("来", "き") or stem.endswith("来"):
        base = stem[:-1] if stem != "き" else ""
        return base + {"dict": "来る", "neg": "来ない", "past": "来た", "negpast": "来なかった"}[form]
    if _suru(stem):
        body = stem[:-1]
        return body + {"dict": "する", "neg": "しない", "past": "した", "negpast": "しなかった"}[form]
    if _ichidan(stem):
        return stem + {"dict": "る", "neg": "ない", "past": "た", "negpast": "なかった"}[form]
    last, body = stem[-1], stem[:-1]
    if last not in _I2U:
        return stem + {"dict": "る", "neg": "ない", "past": "た", "negpast": "なかった"}[form]
    if form == "dict":
        return body + _I2U[last]
    if form == "past":
        if stem.endswith(("行き", "いき")):
            return body + "った"
        return body + _I2TA[last]
    neg = body + _I2A[last] + "ない"
    return neg if form == "neg" else neg[:-1] + "かった"


# 文末の言い方 → ふつうの形
_END_PARTICLES = re.compile(r"(よね|よな|よ|ね|ねえ|なあ|なぁ|(?<=[いだたるうくすつぬむぶ])な|(?<=[いだたる])わ|"
                            r"(?<=[いだたる])さ|ぞ|ぜ|っす|けどね|けど|けれど|けれども|(?<=[いだたる])のに|"
                            r"(?<=[いだた])し|(?<=[いだたる])(もん|もの)|とか|w+|ｗ+|笑)$")
_TAIL_PUNCT = re.compile(r"[。、！？!?…\.・〜ー～\s]+$")


def plain(cl):
    """丁寧な言い方・話しことばの文末を、ふつうの形にそろえる（中身は変えない）。"""
    s = _TAIL_PUNCT.sub("", cl)
    for _ in range(3):
        t = _END_PARTICLES.sub("", s) if len(s) > 3 else s
        if t == s:
            break
        s = _TAIL_PUNCT.sub("", t)
    s = re.sub(r"じゃん$", "じゃない", s)
    s = re.sub(r"な?(ん|の)(です|だ)$", "", s)
    m = re.search(r"(.+?)ませんでした$", s)
    if m:
        return masu_to_plain(m.group(1), "negpast")
    m = re.search(r"(.+?)ました$", s)
    if m:
        return masu_to_plain(m.group(1), "past")
    m = re.search(r"(.+?)ません$", s)
    if m:
        return masu_to_plain(m.group(1), "neg")
    m = re.search(r"(.+?)ます$", s)
    if m:
        return masu_to_plain(m.group(1), "dict")
    s = re.sub(r"(じゃ|では)(なかった|ありませんでした)(です)?$", "ではなかった", s)
    s = re.sub(r"(じゃ|では)(ない|ありません)(です)?$", "ではない", s)
    s = re.sub(r"でした$", "だった", s)
    s = re.sub(r"(い|た|ない|かった)です$", r"\1", s)
    s = re.sub(r"です$", "だ", s)
    s = re.sub(r"な?(ん|の)だ$", "", s)
    return s




# 「〜のですね」の前に置けない形（名詞・な形容詞）は「〜なのですね」にする
_NA_ADJ = ("きれい", "綺麗", "嫌い", "有名", "大丈夫", "平気", "好き", "大好き", "心配", "不安", "暇", "ひま",
           "元気", "静か", "大切", "大事", "無理", "変", "楽", "幸せ", "残念", "必要", "普通", "ふつう", "自由", "苦手",
           "得意", "上手", "下手", "大変", "面倒", "退屈", "最悪", "最高", "一緒", "同じ")
# ひらがなで書く名詞（「た」「い」で終わっていても、動詞・形容詞ではない）
_KANA_NOUN = ("あなた", "わたし", "こと", "もの", "とき", "ところ", "ため", "せい", "ひと", "みんな", "ひとり",
              "ここ", "そこ", "あそこ", "どこ", "いま", "まま", "はず", "わけ", "よう", "ほう", "うち", "ほか",
              "ぜんぶ", "おかげ", "くらい", "ぐらい", "だけ", "ばかり", "ほど", "まで", "など", "たち", "なか")
_VERB_END = tuple("うくぐすつぬぶむる") + ("た", "だ", "ない", "たい", "い")


def nominal(s):
    """名詞（か、な形容詞）で終わっているか。"""
    if not s:
        return False
    if s.endswith(_NA_ADJ) or s.endswith(_KANA_NOUN) or s.endswith(("そう", "みたい", "よう")):
        return True
    if re.search(f"[{KANJI}゠-ヿー]$", s):
        return True
    return not s.endswith(_VERB_END)


# て形・連用で途切れた文 → 言い切り（話の流れの「〜て」は、たいてい過去のできごと）
_TE = (("なくて", "ない"), ("くて", "い"), ("ていて", "ている"), ("でいて", "でいる"),
       ("てしまって", "てしまった"), ("でしまって", "でしまった"), ("ちゃって", "てしまった"), ("じゃって", "でしまった"),
       ("すぎて", "すぎる"), ("過ぎて", "過ぎる"), ("なので", "だ"), ("だから", "だ"))


def te_to_plain(s):
    for a, b in _TE:
        if s.endswith(a):
            return s[: -len(a)] + b
    if s.endswith("から") and nominal(s[:-2]):
        return s                                       # 先月から・子どもの頃から
    if s.endswith(("ので", "から")):
        return s[:-2]
    if s.endswith("で"):
        stem = s[:-1]
        if stem.endswith(("ん", "い")) and not stem.endswith(_NA_ADJ):
            return stem + "だ"                         # 読んで → 読んだ・泳いで → 泳いだ
        if nominal(stem):
            return stem                               # 雨で・仕事で・きれいで
    if s.endswith("て") and len(s) >= 3:
        return s[:-1] + "た"                          # 怒られて → 怒られた・書いて → 書いた
    return None


# ミナモが口にするときの、人の呼び方
